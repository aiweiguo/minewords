export function getGuideById(id: string): Guide | undefined {
  return guides.find((guide) => guide.id === id);
}

export function searchGuides(query: string, category?: GuideCategory | "all") {
  const q = query.trim().toLowerCase();
  return guides.filter((guide) => {
    if (category && category !== "all" && guide.category !== category) {
      return false;
    }
    if (!q) return true;
    const haystack = [
      guide.title,
      guide.titleCn,
      guide.summaryCn,
      guide.simpleEnglish,
      ...guide.keywords.map((k) => `${k.english} ${k.chinese}`),
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(q);
  });
}
